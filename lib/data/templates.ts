/** Шаблонные тексты, которые используются и генератором данных, и демо-режимом ИИ */

export function vacancyText(opts: { title: string; salary: string; biz: string; address: string; hours: string; details?: string }) {
  const { title, salary, biz, address, hours, details } = opts;
  return [
    `🔥 ${biz} ищет: ${title}`,
    "",
    `Мы — команда, которая ценит клиентов и друг друга. Ищем человека, который любит своё дело и хочет расти вместе с нами.`,
    details ? `\nО позиции: ${details}` : "",
    "",
    "Что делать:",
    `• работать с клиентами и поддерживать высокий уровень сервиса;`,
    `• вести учёт в системе (с ней помогает ИИ-ассистент «Салым»);`,
    `• участвовать в развитии и предлагать идеи.`,
    "",
    "Мы ждём:",
    "• опыт от 1 года (рассмотрим и начинающих с горящими глазами);",
    "• аккуратность, пунктуальность, вежливость;",
    "• знание казахского и русского языков.",
    "",
    "Мы предлагаем:",
    `• доход: ${salary};`,
    `• график: ${hours.toLowerCase()}, сменный;`,
    "• официальное оформление и обучение за счёт компании;",
    "• дружный коллектив и стабильный поток клиентов.",
    "",
    `📍 ${address}`,
    "Откликайтесь в WhatsApp или Telegram — ответим в течение 10 минут!",
  ]
    .filter((l, i, arr) => !(l === "" && arr[i - 1] === ""))
    .join("\n");
}
